import assert from "node:assert/strict";
import { getVarynthOrigin, VARYNTH_PUBLIC_ORIGIN, VARYNTH_PUBLIC_URL } from "../config/platform";
import { modules } from "../modules";
assert.equal(VARYNTH_PUBLIC_ORIGIN, "https://varynth-ynqv-plum.vercel.app");
assert.equal(VARYNTH_PUBLIC_URL, "https://varynth-ynqv-plum.vercel.app/dashboard");
assert.equal(getVarynthOrigin("http://localhost:3000"), "http://localhost:3000");
const internalModules = modules.filter((module) => module.id !== "ligahub");
assert.ok(internalModules.length > 0 && internalModules.every((module) => /^\/(modules|projects)(\/|$)/.test(module.href)), "Módulos internos usam somente rotas públicas relativas");
const localExternal = modules.find((module) => module.id === "ligahub");
assert.equal(localExternal?.href, "http://localhost:8000");
console.log("5/5 verificações do endereço público passaram.");
